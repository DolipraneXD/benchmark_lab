"""Generate and launch the LiteLLM proxy from models.yaml.

The proxy exposes every chat model under its benchlab ``id`` at
``http://<host>:<port>/v1``. Harnesses (Inspect, tau2-bench, Harbor, aider, …)
are pointed at it with ``OPENAI_BASE_URL`` / ``OPENAI_API_KEY`` so they all
share one OpenAI-compatible interface and one usage log.
"""

from __future__ import annotations

import os
import shutil
import socket
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

import httpx
import yaml

from benchlab.config import BenchConfig, ModelSpec
from benchlab.llm import endpoint_params

CALLBACK = "benchlab.proxy_logger.benchlab_logger"


def _proxy_litellm_params(spec: ModelSpec) -> dict[str, Any]:
    """Like ``llm.litellm_params`` but with ``os.environ/VAR`` references so the
    generated YAML never contains a key value."""
    p = endpoint_params(spec, f"os.environ/{spec.api_key_env}" if spec.api_key_env else None)
    # extra_params that are *fixed* for the model (e.g. a vendor-specific flag)
    # are applied here too, so harnesses hitting the proxy get the same setup.
    for k, v in spec.extra_params.items():
        if v is not None and k not in ("temperature", "max_tokens"):
            p[k] = v
    return p


def build_proxy_config(
    cfg: BenchConfig, include_embeddings: bool = True, aliases: dict[str, str] | None = None
) -> dict[str, Any]:
    """``aliases`` = {alias_name: model_id}: extra model names routed to the same
    upstream (harnesses that dispatch on the model name prefix, e.g. OSWorld's
    agent only speaks OpenAI chat for names starting with ``gpt``)."""
    model_list = []
    for alias, target in (aliases or {}).items():
        m = cfg.get(target)
        model_list.append(
            {
                "model_name": alias,
                "litellm_params": _proxy_litellm_params(m),
                "model_info": {
                    "id": m.id,
                    "benchlab_name": m.name,
                    "self_hosted": m.self_hosted,
                    "mode": "chat",
                    "alias_of": m.id,
                },
            }
        )
    for m in cfg.models:
        if m.reference:
            continue  # published scores only, never called
        if m.kind == "reranker":
            continue  # /v1/rerank is called directly by the retrieval pipeline
        if m.kind == "embedding" and (not include_embeddings or m.base_url == "local"):
            continue
        entry = {
            "model_name": m.id,
            "litellm_params": _proxy_litellm_params(m),
            "model_info": {
                "id": m.id,
                "benchlab_name": m.name,
                "self_hosted": m.self_hosted,
                "mode": "embedding" if m.kind == "embedding" else "chat",
            },
        }
        model_list.append(entry)
    return {
        "model_list": model_list,
        "litellm_settings": {
            "drop_params": True,
            "num_retries": 2,
            "request_timeout": cfg.settings.request_timeout_s,
            "callbacks": [CALLBACK],
            "turn_off_message_logging": True,  # usage only; prompts stay out of the proxy logs
        },
        "general_settings": {
            "master_key": "os.environ/LITELLM_MASTER_KEY",
            "store_model_in_db": False,
            "disable_spend_logs": True,  # we keep our own JSONL; no DB needed
        },
    }


def write_proxy_config(
    cfg: BenchConfig,
    path: str | Path = "workspace/litellm_config.yaml",
    aliases: dict[str, str] | None = None,
) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    data = build_proxy_config(cfg, aliases=aliases)
    text = yaml.safe_dump(data, sort_keys=False)
    assert "sk-" not in text.replace("os.environ/", "")  # belt and braces
    p.write_text("# GENERATED by `benchlab proxy-config` from models.yaml - do not edit\n" + text)
    return p


def proxy_base_url(cfg: BenchConfig) -> str:
    s = cfg.settings
    return f"http://{s.litellm_proxy_host}:{s.litellm_proxy_port}/v1"


def proxy_env(cfg: BenchConfig) -> dict[str, str]:
    """Env vars a harness needs to talk to the proxy."""
    return {
        "OPENAI_BASE_URL": proxy_base_url(cfg),
        "OPENAI_API_BASE": proxy_base_url(cfg),
        "OPENAI_API_KEY": os.environ.get("LITELLM_MASTER_KEY", "sk-benchlab-local"),
    }


class ProxyProcess:
    """A LiteLLM proxy owned by one run.

    Started on a free port with ``BENCHLAB_USAGE_LOG`` pointing at the run's
    ``usage.jsonl``, so every harness request is attributed to that run without
    sharing state with a long-lived proxy. Use as a context manager.
    """

    def __init__(
        self,
        cfg: BenchConfig,
        work_dir: Path,
        usage_log: Path,
        port: int | None = None,
        aliases: dict[str, str] | None = None,
    ):
        self.cfg = cfg
        self.aliases = aliases
        self.work_dir = Path(work_dir)
        self.usage_log = Path(usage_log)
        self.port = port or _free_port()
        # in a run container, other containers (Aider's) must reach the proxy: listen on all
        # interfaces and advertise the container's name on the Docker network
        advertise = os.environ.get("BENCHLAB_ADVERTISE_HOST")
        self.bind = "0.0.0.0" if advertise else cfg.settings.litellm_proxy_host
        self.host = advertise or cfg.settings.litellm_proxy_host
        self.proc: subprocess.Popen | None = None
        self.log_path = self.work_dir / "proxy.log"
        self.master_key = os.environ.get("LITELLM_MASTER_KEY") or "sk-benchlab-local"

    @property
    def base_url(self) -> str:
        return f"http://{self.host}:{self.port}/v1"

    def env_for_harness(self) -> dict[str, str]:
        return {
            "OPENAI_BASE_URL": self.base_url,
            "OPENAI_API_BASE": self.base_url,
            "OPENAI_API_KEY": self.master_key,
        }

    def start(self, timeout_s: float = 120.0) -> ProxyProcess:
        exe = shutil.which("litellm")
        if exe is None:
            raise RuntimeError("litellm proxy CLI not found; run `uv sync`")
        self.work_dir.mkdir(parents=True, exist_ok=True)
        cfg_path = write_proxy_config(
            self.cfg, self.work_dir / "litellm_config.yaml", aliases=self.aliases
        )
        env = dict(os.environ)
        env["BENCHLAB_USAGE_LOG"] = str(self.usage_log)
        env["LITELLM_MASTER_KEY"] = self.master_key
        env.setdefault("LITELLM_LOG", "ERROR")
        self.proc = subprocess.Popen(
            [exe, "--config", str(cfg_path), "--host", self.bind, "--port", str(self.port)],
            stdout=open(self.log_path, "ab"),
            stderr=subprocess.STDOUT,
            env=env,
        )
        deadline = time.time() + timeout_s
        while time.time() < deadline:
            if self.proc.poll() is not None:
                raise RuntimeError(
                    f"proxy exited early (rc={self.proc.returncode}); see {self.log_path}"
                )
            if self.healthy():
                return self
            time.sleep(0.5)
        self.stop()
        raise RuntimeError(f"proxy did not become healthy in {timeout_s}s; see {self.log_path}")

    def healthy(self) -> bool:
        try:
            r = httpx.get(f"http://{self.host}:{self.port}/health/liveliness", timeout=2.0)
            return r.status_code == 200
        except httpx.HTTPError:
            return False

    def stop(self) -> None:
        if self.proc and self.proc.poll() is None:
            self.proc.terminate()
            try:
                self.proc.wait(timeout=15)
            except subprocess.TimeoutExpired:
                self.proc.kill()
        self.proc = None

    def __enter__(self) -> ProxyProcess:
        return self.start()

    def __exit__(self, *exc) -> None:
        self.stop()


def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def launch_proxy(
    cfg: BenchConfig, config_path: Path, detach: bool = False
) -> subprocess.Popen | int:
    exe = shutil.which("litellm")
    if exe is None:
        print(
            "litellm proxy CLI not found. Run: uv sync",
            file=sys.stderr,
        )
        return 2
    os.environ.setdefault("LITELLM_MASTER_KEY", "sk-benchlab-local")
    cmd = [
        exe,
        "--config",
        str(config_path),
        "--host",
        cfg.settings.litellm_proxy_host,
        "--port",
        str(cfg.settings.litellm_proxy_port),
    ]
    if detach:
        return subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return subprocess.call(cmd)
