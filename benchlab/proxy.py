"""Generate and launch the LiteLLM proxy from models.yaml.

The proxy exposes every chat model under its benchlab ``id`` at
``http://<host>:<port>/v1``. Harnesses (Inspect, tau2-bench, Harbor, aider, …)
are pointed at it with ``OPENAI_BASE_URL`` / ``OPENAI_API_KEY`` so they all
share one OpenAI-compatible interface and one usage log.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

from benchlab.config import BenchConfig, ModelSpec
from benchlab.llm import litellm_model_name

CALLBACK = "benchlab.proxy_logger.benchlab_logger"


def _proxy_litellm_params(spec: ModelSpec) -> dict[str, Any]:
    """Like ``llm.litellm_params`` but with ``os.environ/VAR`` references so the
    generated YAML never contains a key value."""
    p: dict[str, Any] = {"model": litellm_model_name(spec)}
    if spec.provider == "openai_compatible":
        p["api_base"] = spec.base_url
        p["api_key"] = f"os.environ/{spec.api_key_env}"
    elif spec.provider == "anthropic":
        p["api_key"] = f"os.environ/{spec.api_key_env}"
        if spec.base_url:
            p["api_base"] = spec.base_url
    elif spec.provider == "bedrock":
        if spec.region:
            p["aws_region_name"] = spec.region
    if spec.extra_headers:
        p["extra_headers"] = dict(spec.extra_headers)
    if spec.has_prices:
        p["input_cost_per_token"] = spec.price_in_per_mtok / 1e6
        p["output_cost_per_token"] = spec.price_out_per_mtok / 1e6
    # extra_params that are *fixed* for the model (e.g. a vendor-specific flag)
    # are applied here too, so harnesses hitting the proxy get the same setup.
    for k, v in spec.extra_params.items():
        if v is not None and k not in ("temperature", "max_tokens"):
            p[k] = v
    return p


def build_proxy_config(cfg: BenchConfig, include_embeddings: bool = True) -> dict[str, Any]:
    model_list = []
    for m in cfg.models:
        if m.kind == "reranker":
            continue  # /v1/rerank is called directly by the retrieval pipeline
        if m.kind == "embedding" and (not include_embeddings or m.base_url == "local"):
            continue
        entry = {
            "model_name": m.id,
            "litellm_params": _proxy_litellm_params(m),
            "model_info": {
                "id": m.id,
                "benchlab_name": m.name,
                "self_hosted": m.self_hosted,
                "mode": "embedding" if m.kind == "embedding" else "chat",
            },
        }
        model_list.append(entry)
    return {
        "model_list": model_list,
        "litellm_settings": {
            "drop_params": True,
            "num_retries": 2,
            "request_timeout": cfg.settings.request_timeout_s,
            "callbacks": [CALLBACK],
            "turn_off_message_logging": True,  # usage only; prompts stay out of the proxy logs
        },
        "general_settings": {
            "master_key": "os.environ/LITELLM_MASTER_KEY",
            "store_model_in_db": False,
            "disable_spend_logs": True,  # we keep our own JSONL; no DB needed
        },
    }


def write_proxy_config(cfg: BenchConfig, path: str | Path = "litellm_config.yaml") -> Path:
    p = Path(path)
    data = build_proxy_config(cfg)
    text = yaml.safe_dump(data, sort_keys=False)
    assert "sk-" not in text.replace("os.environ/", "")  # belt and braces
    p.write_text("# GENERATED by `benchlab proxy-config` from models.yaml - do not edit\n" + text)
    return p


def proxy_base_url(cfg: BenchConfig) -> str:
    s = cfg.settings
    return f"http://{s.litellm_proxy_host}:{s.litellm_proxy_port}/v1"


def proxy_env(cfg: BenchConfig) -> dict[str, str]:
    """Env vars a harness needs to talk to the proxy."""
    return {
        "OPENAI_BASE_URL": proxy_base_url(cfg),
        "OPENAI_API_BASE": proxy_base_url(cfg),
        "OPENAI_API_KEY": os.environ.get("LITELLM_MASTER_KEY", "sk-benchlab-local"),
    }


def launch_proxy(
    cfg: BenchConfig, config_path: Path, detach: bool = False
) -> subprocess.Popen | int:
    exe = shutil.which("litellm")
    if exe is None:
        print(
            "litellm proxy CLI not found. Run: uv sync",
            file=sys.stderr,
        )
        return 2
    os.environ.setdefault("LITELLM_MASTER_KEY", "sk-benchlab-local")
    cmd = [
        exe,
        "--config",
        str(config_path),
        "--host",
        cfg.settings.litellm_proxy_host,
        "--port",
        str(cfg.settings.litellm_proxy_port),
    ]
    if detach:
        return subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return subprocess.call(cmd)
