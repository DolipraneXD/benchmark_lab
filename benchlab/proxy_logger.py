"""LiteLLM proxy callback: logs every harness request to benchlab's usage log.

Loaded by the proxy through ``litellm_settings.callbacks:
["benchlab.proxy_logger.benchlab_logger"]`` (generated by ``benchlab proxy-config``).
The log path comes from ``BENCHLAB_USAGE_LOG`` (default ``runs/proxy_usage.jsonl``);
``benchlab run`` points it at the active run folder so cost is attributed per run.
"""

from __future__ import annotations

import collections
import threading
import time
from typing import Any

from litellm.integrations.custom_logger import CustomLogger

from benchlab.redact import redact
from benchlab.usage import UsageLog, UsageRecord, default_proxy_log_path

BENCHLAB_HEADERS = ("x-benchlab-run", "x-benchlab-bench", "x-benchlab-task")


def _seconds(a, b) -> float | None:
    try:
        return (a - b).total_seconds()
    except Exception:  # noqa: BLE001
        return None


def _record(
    kwargs: dict[str, Any], response_obj: Any, start_time, end_time, failed: bool
) -> UsageRecord:
    slo = kwargs.get("standard_logging_object") or {}
    usage = getattr(response_obj, "usage", None)
    tin = int(slo.get("prompt_tokens") or getattr(usage, "prompt_tokens", 0) or 0)
    tout = int(slo.get("completion_tokens") or getattr(usage, "completion_tokens", 0) or 0)
    latency = _seconds(end_time, start_time) or 0.0

    # LiteLLM sets completion_startTime == end for non-streamed calls; only
    # a streamed request has a real time-to-first-token.
    ttft = None
    if kwargs.get("stream") or slo.get("stream"):
        cst = slo.get("completion_startTime") or kwargs.get("completion_start_time")
        if cst is not None and start_time is not None:
            ttft = _seconds(cst, start_time)

    cost = kwargs.get("response_cost")
    if cost is None:
        cost = slo.get("response_cost")
    # A zero cost with real token usage means "no price known", not "free".
    if cost is not None and float(cost) == 0.0 and (tin + tout) > 0:
        cost = None

    status = "ok"
    etype = emsg = None
    if failed:
        exc = kwargs.get("exception")
        etype = type(exc).__name__ if exc is not None else "error"
        emsg = redact(str(exc))[:2000] if exc is not None else slo.get("error_str")
        low = etype.lower()
        status = "timeout" if "timeout" in low else "rate_limit" if "ratelimit" in low else "error"

    n_tc = 0
    try:
        msg = response_obj.choices[0].message
        n_tc = len(getattr(msg, "tool_calls", None) or [])
    except Exception:  # noqa: BLE001
        pass

    tags: dict[str, Any] = {
        "proxy": True,
        "model_group": slo.get("model_group") or kwargs.get("model"),
        "user_agent": (slo.get("metadata") or {}).get("user_agent"),
        "call_id": kwargs.get("litellm_call_id"),
    }
    # harness-side attribution headers (set by adapters), nothing else from the request
    req_meta = (slo.get("metadata") or {}).get("requester_metadata") or {}
    hdrs = req_meta.get("headers") if isinstance(req_meta, dict) else None
    if not hdrs:
        meta = (kwargs.get("litellm_params") or {}).get("metadata") or {}
        hdrs = meta.get("headers") if isinstance(meta, dict) else None
    for h in BENCHLAB_HEADERS:
        if hdrs and h in hdrs:
            tags[h] = hdrs[h]

    return UsageRecord(
        ts=time.time(),
        model_id=str(slo.get("model_group") or kwargs.get("model") or "?"),
        litellm_model=str(slo.get("model") or kwargs.get("model") or "?"),
        call_type="proxy",
        status=status,
        latency_s=latency,
        ttft_s=ttft,
        tokens_in=tin,
        tokens_out=tout,
        cost_usd=float(cost) if cost is not None else None,
        finish_reason=None,
        n_tool_calls=n_tc,
        error_type=etype,
        error_msg=emsg,
        tags=tags,
    )


class BenchLabProxyLogger(CustomLogger):
    """Writes one usage record per proxied request; the proxy may fire both the
    sync and async hook for one call, so records are de-duplicated by call id."""

    def __init__(self) -> None:
        super().__init__()
        self._log: UsageLog | None = None
        self._seen: collections.OrderedDict[tuple[str, bool], None] = collections.OrderedDict()
        self._lock = threading.Lock()

    def _get_log(self) -> UsageLog:
        # resolved lazily so BENCHLAB_USAGE_LOG can be set after import
        if self._log is None or self._log.path != default_proxy_log_path():
            self._log = UsageLog(default_proxy_log_path())
        return self._log

    def _first_time(self, kwargs: dict[str, Any], failed: bool) -> bool:
        call_id = kwargs.get("litellm_call_id")
        if not call_id:
            return True
        key = (str(call_id), failed)
        with self._lock:
            if key in self._seen:
                return False
            self._seen[key] = None
            while len(self._seen) > 10_000:
                self._seen.popitem(last=False)
        return True

    def _write(self, kwargs, response_obj, start_time, end_time, failed: bool) -> None:
        if self._first_time(kwargs, failed):
            self._get_log().append(_record(kwargs, response_obj, start_time, end_time, failed))

    def log_success_event(self, kwargs, response_obj, start_time, end_time):
        self._write(kwargs, response_obj, start_time, end_time, failed=False)

    def log_failure_event(self, kwargs, response_obj, start_time, end_time):
        self._write(kwargs, response_obj, start_time, end_time, failed=True)

    async def async_log_success_event(self, kwargs, response_obj, start_time, end_time):
        self._write(kwargs, response_obj, start_time, end_time, failed=False)

    async def async_log_failure_event(self, kwargs, response_obj, start_time, end_time):
        self._write(kwargs, response_obj, start_time, end_time, failed=True)


benchlab_logger = BenchLabProxyLogger()
